#!/bin/bash
# ============================================================
# StallFront container entrypoint
#
# - Prepares /data: .env (generated settings), storage/ (uploads, logs,
#   cache, sessions) and mysql/ (embedded database).
# - DB_HOST not set: starts the embedded MariaDB. On the first start it
#   creates the database and a user with a random password, saved in
#   /data/.env and reused on every following start.
# - DB_HOST set: uses that external MySQL/MariaDB or PostgreSQL server.
# - Generates APP_KEY and the browser-notification (VAPID) keys once.
# - Applies the database migrations, starts cron for the scheduler and
#   runs Apache in the foreground.
# ============================================================
set -euo pipefail

APP=/var/www/html
DATA="${STALLFRONT_DATA_DIR:-/data}"
ENV_FILE="$DATA/.env"
MYSQL_DATA="$DATA/mysql"
SOCKET=/run/mysqld/mysqld.sock
INTERNAL_DB_NAME=stallfront
INTERNAL_DB_USER=stallfront

log() { echo "[stallfront] $*"; }

cd "$APP"

# ── Persistent folders ──────────────────────────────────────
mkdir -p "$DATA/storage/app/public" "$DATA/storage/app/private" "$DATA/storage/logs" \
         "$DATA/storage/framework/cache/data" "$DATA/storage/framework/sessions" "$DATA/storage/framework/views"
touch "$ENV_FILE"
chown -R www-data:www-data "$DATA/storage" 2> /dev/null \
  || log "WARNING: cannot change the owner of $DATA/storage (check the volume permissions)"
chown root:www-data "$ENV_FILE" 2> /dev/null || true
chmod 640 "$ENV_FILE" 2> /dev/null || true

# Value of a key in /data/.env ('' if missing)
env_get() {
  sed -n "s/^$1=//p" "$ENV_FILE" | tail -n 1 | sed -e 's/^"\(.*\)"$/\1/'
}

# Adds or replaces a key in /data/.env
env_set() {
  local key="$1" value="$2" tmp
  tmp="$(mktemp)"
  grep -v "^$key=" "$ENV_FILE" > "$tmp" || true
  printf '%s=%s\n' "$key" "$value" >> "$tmp"
  cat "$tmp" > "$ENV_FILE"
  rm -f "$tmp"
}

if ! grep -q '^# StallFront' "$ENV_FILE"; then
  {
    echo "# StallFront settings generated by the container. Keep this file with the data."
    echo "# Environment variables with the same names take precedence."
    cat "$ENV_FILE"
  } > "$ENV_FILE.tmp" && cat "$ENV_FILE.tmp" > "$ENV_FILE" && rm -f "$ENV_FILE.tmp"
fi

# ── Application key and browser-notification keys (generated once) ──
if [ -z "${APP_KEY:-}" ] && [ -z "$(env_get APP_KEY)" ]; then
  env_set APP_KEY "base64:$(php -r 'echo base64_encode(random_bytes(32));')"
  log "Generated the application key (stored in $ENV_FILE)"
fi

if [ -z "${VAPID_PUBLIC_KEY:-}" ] && [ -z "$(env_get VAPID_PUBLIC_KEY)" ]; then
  if keys="$(php -r 'require "vendor/autoload.php"; $k = Minishlink\WebPush\VAPID::createVapidKeys(); echo $k["publicKey"], " ", $k["privateKey"];' 2> /dev/null)"; then
    env_set VAPID_PUBLIC_KEY "${keys% *}"
    env_set VAPID_PRIVATE_KEY "${keys#* }"
    log "Generated the browser notification keys"
  else
    log "WARNING: could not generate the browser notification keys; notifications will use email only"
  fi
fi

# ── Database ────────────────────────────────────────────────
use_internal_db() {
  [ -z "${DB_HOST:-}" ] || return 1
  local configured
  configured="$(env_get DB_HOST)"
  [ -z "$configured" ] || [ "$(env_get DB_INTERNAL)" = "1" ]
}

start_internal_db() {
  mkdir -p "$MYSQL_DATA" /run/mysqld
  chown -R mysql:mysql "$MYSQL_DATA" /run/mysqld 2> /dev/null \
    || log "WARNING: cannot change the owner of $MYSQL_DATA (MariaDB needs to write there)"

  if [ ! -d "$MYSQL_DATA/mysql" ]; then
    log "Initialising the embedded MariaDB in $MYSQL_DATA"
    mariadb-install-db --user=mysql --datadir="$MYSQL_DATA" \
      --auth-root-authentication-method=socket --skip-test-db > /dev/null
  fi

  log "Starting the embedded MariaDB"
  mariadbd-safe --user=mysql --datadir="$MYSQL_DATA" --socket="$SOCKET" \
    --bind-address=127.0.0.1 --port=3306 \
    --character-set-server=utf8mb4 --collation-server=utf8mb4_unicode_ci \
    --log-error="$DATA/storage/logs/mariadb.log" > /dev/null 2>&1 &
  MARIADB_PID=$!

  for _ in $(seq 1 60); do
    if mariadb-admin --socket="$SOCKET" ping > /dev/null 2>&1; then break; fi
    sleep 1
  done
  if ! mariadb-admin --socket="$SOCKET" ping > /dev/null 2>&1; then
    log "ERROR: MariaDB did not start. See $DATA/storage/logs/mariadb.log"
    exit 1
  fi

  # Password: generated once, then always read back from /data/.env
  local pass
  pass="$(env_get DB_PASSWORD)"
  if [ -z "$pass" ]; then
    pass="$(php -r 'echo bin2hex(random_bytes(24));')"
    log "First start: created the database with a generated password (stored in $ENV_FILE)"
  fi

  # Idempotent: also realigns the password with /data/.env
  mariadb --socket="$SOCKET" <<SQL
CREATE DATABASE IF NOT EXISTS \`$INTERNAL_DB_NAME\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '$INTERNAL_DB_USER'@'127.0.0.1' IDENTIFIED BY '$pass';
CREATE USER IF NOT EXISTS '$INTERNAL_DB_USER'@'localhost' IDENTIFIED BY '$pass';
ALTER USER '$INTERNAL_DB_USER'@'127.0.0.1' IDENTIFIED BY '$pass';
ALTER USER '$INTERNAL_DB_USER'@'localhost' IDENTIFIED BY '$pass';
GRANT ALL PRIVILEGES ON \`$INTERNAL_DB_NAME\`.* TO '$INTERNAL_DB_USER'@'127.0.0.1';
GRANT ALL PRIVILEGES ON \`$INTERNAL_DB_NAME\`.* TO '$INTERNAL_DB_USER'@'localhost';
FLUSH PRIVILEGES;
SQL

  env_set DB_INTERNAL 1
  env_set DB_CONNECTION mysql
  env_set DB_HOST 127.0.0.1
  env_set DB_PORT 3306
  env_set DB_DATABASE "$INTERNAL_DB_NAME"
  env_set DB_USERNAME "$INTERNAL_DB_USER"
  env_set DB_PASSWORD "$pass"
}

MARIADB_PID=""
if use_internal_db; then
  start_internal_db
else
  log "Using the external database ${DB_CONNECTION:-$(env_get DB_CONNECTION)} at ${DB_HOST:-$(env_get DB_HOST)}"
fi

# ── Application ─────────────────────────────────────────────
rm -rf public/storage
php artisan storage:link > /dev/null
su -s /bin/bash www-data -c "php artisan optimize:clear" > /dev/null || true

migrated=0
for attempt in $(seq 1 30); do
  if su -s /bin/bash www-data -c "php artisan migrate --force"; then
    migrated=1
    break
  fi
  log "Database not ready yet (attempt $attempt), retrying in 3 seconds"
  sleep 3
done
if [ "$migrated" != 1 ]; then
  log "ERROR: the database migrations failed. Check the DB_* settings."
  exit 1
fi

su -s /bin/bash www-data -c "php artisan config:cache && php artisan route:cache && php artisan view:cache" > /dev/null \
  || log "WARNING: could not cache the configuration; the app still works, a bit slower"

# ── Scheduler (cron every minute) ───────────────────────────
# Cron does not inherit the container environment: it is saved in a file
# readable only by root and www-data and loaded at every run.
export -p | grep -vE '^declare -x (PWD|OLDPWD|SHLVL|_|HOSTNAME|TERM|HOME)=' > /etc/stallfront.env
chown root:www-data /etc/stallfront.env
chmod 0640 /etc/stallfront.env
echo "* * * * * www-data bash -c '. /etc/stallfront.env; cd $APP && php artisan schedule:run' > /dev/null 2>> $DATA/storage/logs/cron-errors.log" > /etc/cron.d/stallfront
chmod 0644 /etc/cron.d/stallfront
service cron start > /dev/null

# ── Apache in the foreground, clean shutdown of both services ──
shutdown() {
  log "Stopping"
  [ -n "${APACHE_PID:-}" ] && kill -WINCH "$APACHE_PID" 2> /dev/null || true
  if [ -n "$MARIADB_PID" ]; then
    mariadb-admin --socket="$SOCKET" shutdown > /dev/null 2>&1 || true
  fi
  wait || true
  exit 0
}
trap shutdown TERM INT

"$@" &
APACHE_PID=$!
wait "$APACHE_PID"
